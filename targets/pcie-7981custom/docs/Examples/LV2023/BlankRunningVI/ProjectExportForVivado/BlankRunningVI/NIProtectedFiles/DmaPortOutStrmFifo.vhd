      kRdPortWidth              => kRdPortWidth,               -- in  natural := 8
      kFifoCountWidth           => kFifoCountWidth,            -- in  natural
      kCorrelatedDataWidth      => kCorrelatedDataWidth,       -- in  integer := 0
      kCorrelatedDataResetValue => kCorrelatedDataResetValue)  -- in  std_logic_vector
    port map (
      aReset              => aReset,               -- in  boolean
      IClk                => IClk,                 -- in  std_logic
      iReset              => iReset,               -- in  boolean
      iWrite              => iWrite,               -- in  boolean
      iAddr               => iAddr,                -- out unsigned(kAddressWidth-1 downto
      iCorrelatedDataIn   => iCorrelatedDataIn,    -- in  std_logic_vector(kCorrelatedDat
      iWriteLengthInBytes => iWriteLengthInBytes,  -- in  NiDmaBusByteCount_t
      iRsrvWriteSpaces    => iRsrvWriteSpaces,     -- in  boolean
      iReqWriteSamples    => iReqWriteSpaces,      -- in  unsigned(kFifoCountWidth-1 down
      iRsrvdSpacesFilled  => iRsrvdSpacesFilled,   -- out boolean
      OClk                => OClk,                 -- in  std_logic
      oReset              => oReset,               -- in  boolean
      oRead               => oRead,                -- in  boolean
      oAddr               => oAddr,                -- out unsigned(kFifoCountWidth-1 down
      oCorrelatedDataOut  => oCorrelatedDataOut,   -- out std_logic_vector(kCorrelatedDat
      iEmptyCount         => iEmptyCount,          -- out unsigned(kFifoCountWidth-1 down
      oFullCount          => oFullCount);          -- out unsigned(kFifoCountWidth-1 down

  -----------------------------------------------------------------------------
  -- Instantiate the dual port RAM module
  -----------------------------------------------------------------------------

  --vhook_e DmaPortOutStrmDPRAM
  DmaPortOutStrmDPRAMx: entity work.DmaPortOutStrmDPRAM (rtl)
    generic map (
      kAddressWidth        => kAddressWidth,         -- in  natural := 6
      kSampleSize          => kSampleSize,           -- in  natural := 8
      kNumOfSamplesPerRead => kNumOfSamplesPerRead,  -- in  natural := 1
      kRdPortWidth         => kRdPortWidth,          -- in  natural := 8
      kFifoCountWidth      => kFifoCountWidth)       -- in  natural

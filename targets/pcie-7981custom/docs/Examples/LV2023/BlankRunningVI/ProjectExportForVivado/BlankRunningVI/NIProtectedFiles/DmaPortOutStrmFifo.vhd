      OClk          => OClk,           -- in  std_logic
      oReset        => oReset,         -- in  boolean
      oAddr         => oAddr,          -- in  unsigned(kFifoCountWidth-1 downto 0)
      oDataOut      => oDataOut);      -- out std_logic_vector(kRdPortWidth-1 downto 0)


end rtl;
